/* ---------------------------------------------------------------------------
   notebooks.js — Downloadable reproducible analysis notebooks.

   Lists the notebooks generated by scripts/export_notebook.py (via
   /api/notebooks) and lets the user download each as a .ipynb file. The files
   are static build artifacts served by the API; nothing is generated in the
   browser.

   Degrades gracefully: on file:// or when the API is unreachable it shows a
   short explanatory note instead of broken buttons.
   --------------------------------------------------------------------------- */

function _notebooksUnavailable(message) {
  var host = document.getElementById("notebook-list");
  if (host) host.innerHTML = "<em>" + message + "</em>";
}

function downloadNotebook(slug, filename) {
  fetch("/api/notebooks/" + encodeURIComponent(slug))
    .then(function(r) {
      if (!r.ok) throw new Error("HTTP " + r.status);
      return r.json();
    })
    .then(function(nb) {
      var blob = new Blob([JSON.stringify(nb, null, 1)], {
        type: "application/x-ipynb+json",
      });
      var url = URL.createObjectURL(blob);
      var a = document.createElement("a");
      a.href = url;
      a.download = filename;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      setTimeout(function() { URL.revokeObjectURL(url); }, 1000);
    })
    .catch(function() {
      window.alert("Notebook download requires the API server to be reachable.");
    });
}

function _notebookCard(nb) {
  var card = document.createElement("div");
  card.className = "notebook-card";

  var title = document.createElement("div");
  title.className = "notebook-card-title";
  title.textContent = nb.title || nb.slug;
  card.appendChild(title);

  if (nb.description) {
    var desc = document.createElement("div");
    desc.className = "notebook-card-desc";
    desc.textContent = nb.description;
    card.appendChild(desc);
  }

  var btn = document.createElement("button");
  btn.type = "button";
  btn.className = "tool-btn tool-btn-sm";
  btn.textContent = "Download .ipynb";
  btn.addEventListener("click", function() {
    downloadNotebook(nb.slug, nb.filename || nb.slug + ".ipynb");
  });
  card.appendChild(btn);

  return card;
}

function initNotebookDownloads() {
  var host = document.getElementById("notebook-list");
  if (!host) return;
  if (typeof window !== "undefined" && window.location.protocol === "file:") {
    _notebooksUnavailable("Notebook downloads are available on the hosted site.");
    return;
  }
  fetch("/api/notebooks")
    .then(function(r) {
      if (!r.ok) throw new Error("HTTP " + r.status);
      return r.json();
    })
    .then(function(list) {
      if (!Array.isArray(list) || !list.length) {
        _notebooksUnavailable("No notebooks are available.");
        return;
      }
      host.innerHTML = "";
      list.forEach(function(nb) { host.appendChild(_notebookCard(nb)); });
    })
    .catch(function() {
      _notebooksUnavailable("Notebooks are unavailable (API offline).");
    });
}

// Hook into init (preserve any previously installed wrapper).
var _origInitToolkit_nb = (typeof initToolkit === "function") ? initToolkit : null;
initToolkit = function() {
  if (_origInitToolkit_nb) _origInitToolkit_nb();
  initNotebookDownloads();
};
